import { build } from 'esbuild';
import { chromium } from 'playwright';
import { readFile, mkdir } from 'node:fs/promises';
import { createServer } from 'node:http';
import assert from 'node:assert/strict';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const qaDir = join(tmpdir(), 'pixelmap-qa');
const css = (await postcss([tailwind()]).process(await readFile('src/app/globals.css', 'utf8'), { from: 'src/app/globals.css' })).css;

const result = await build({ entryPoints: ['tests/browser-entry.tsx'], bundle: true, format: 'iife', globalName: 'editorTests', platform: 'browser', write: false, define: { 'process.env.NODE_ENV': '"development"', 'process.env': '{}' }, jsx: 'automatic' });
const html = '<!doctype html><html><head><link rel="stylesheet" href="/style.css"></head><body style="background:#111;color:white;font:13px sans-serif"><div id="root"></div><script src="/tests.js"></script></body></html>';
const server = createServer((req, res) => { res.setHeader('Content-Type', req.url === '/tests.js' ? 'application/javascript' : req.url === '/style.css' ? 'text/css' : 'text/html'); res.end(req.url === '/tests.js' ? result.outputFiles[0].text : req.url === '/style.css' ? css : html); });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, channel: "chromium" });
  const page = await browser.newPage({ viewport: { width: 1480, height: 1000 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', e => { errors.push(e.message); console.error('Browser error:', e.message); });
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const fixture = await readFile('tests/fixtures/resolume.xml', 'utf8');
  console.log(await page.evaluate(xml => window.editorTests.runChecks(xml), fixture));
  await mkdir(qaDir, { recursive: true });
  await page.locator('#contact-sheet').screenshot({ path: join(qaDir, 'test-cards.png') });
  console.log(await page.evaluate(() => window.editorTests.rotationRegression()));
  await page.locator('#rotation-sheet').screenshot({ path: join(qaDir, 'rotation.png') });
  console.log(await page.evaluate(xml => window.editorTests.cabinetRegression(xml), fixture));
  console.log(await page.evaluate(() => window.editorTests.overlayLogoRegression()));
  await page.locator('#overlay-logo-sheet').screenshot({ path: join(qaDir, 'overlay-logo.png') });
  await page.locator('#cabinet-regression').screenshot({ path: join(qaDir, 'cabinet-903x1280.png') });
  await page.evaluate(() => window.editorTests.mount());
  await page.getByRole('button', { name: 'USE NATIVE CABINET SIZE', exact: true }).waitFor();
  assert.equal(await page.getByText('Columns', { exact: true }).locator('..').locator('input').inputValue(), '7');
  assert.equal(await page.getByText('Rows', { exact: true }).locator('..').locator('input').inputValue(), '10');
  const preset = page.getByText('Cabinet Preset', { exact: true }).locator('..').locator('select');
  await preset.selectOption('p625-500');
  await preset.selectOption('p391-500');
  assert.equal(await page.getByText('Columns', { exact: true }).locator('..').locator('input').inputValue(), '7');
  await page.getByRole('button', { name: 'USE NATIVE CABINET SIZE', exact: true }).click();
  assert.equal(await page.evaluate(() => window.editorTests.state().screens[0].width), 896);
  const columns = page.getByText('Columns', { exact: true }).locator('..').locator('input');
  await columns.fill('8'); await columns.blur();
  assert.equal(await page.evaluate(() => window.editorTests.state().screens[0].width), 1024);
  const grid = page.getByText('Grid Source', { exact: true }).locator('..').locator('select');
  await grid.selectOption('custom');
  await page.getByText('Graphic Grid Size', { exact: true }).waitFor();
  await grid.selectOption('cabinet');
  const patternBeforeOverlay = await page.evaluate(() => JSON.stringify(window.editorTests.state().screens[0].pattern));
  await page.getByRole('button', { name: 'Wire Tunnel', exact: true }).click();
  assert.equal(await page.evaluate(() => JSON.stringify(window.editorTests.state().screens[0].pattern)), patternBeforeOverlay);
  await page.getByRole('slider', { name: 'Overlay Opacity', exact: true }).fill('25');
  assert.equal(await page.evaluate(() => window.editorTests.state().screens[0].animation.opacity), 0.25);
  assert(await page.evaluate(() => window.editorTests.state().screens.every(s => s.animation.type === 'wire-tunnel')));
  await page.getByRole('button', { name: 'Festival • Magenta / Lime', exact: true }).click();
  assert(await page.evaluate(() => !window.editorTests.state().previewPlaying && window.editorTests.state().screens.every(s => s.pattern.type === 'festival-card')));
  await page.evaluate(() => window.editorTests.state().selectScreen(window.editorTests.state().screens[0].id));
  await page.getByText('Center Badge Text', { exact: true }).waitFor();
  const badge = page.getByText('Center Badge Text', { exact: true }).locator('..').locator('input');
  await badge.fill('VJM'); await badge.blur();
  assert(await page.evaluate(() => window.editorTests.state().screens[0].pattern.badgeText === 'VJM'));
  const centerMode = page.getByText('Center Mode', { exact: true }).locator('..').locator('select');
  await centerMode.selectOption('logo');
  await page.getByText('Logo Template', { exact: true }).locator('..').locator('select').selectOption('diamond');
  await page.getByText('Logo Text', { exact: true }).locator('..').locator('input').fill('LIVE');
  await page.getByLabel('Rotate', { exact: true }).check();
  await page.getByRole('button', { name: 'PREVIEW LOGO MOTION', exact: true }).click();
  assert(await page.evaluate(() => window.editorTests.state().screens[0].pattern.logoTemplate === 'diamond' && window.editorTests.state().screens[0].pattern.logoRotate));
  await page.getByText('Logo Template', { exact: true }).locator('..').locator('select').selectOption('upload');
  await page.getByLabel('Upload Center Logo', { exact: true }).setInputFiles(join(qaDir, 'test-cards.png'));
  await page.waitForFunction(() => window.editorTests.state().screens[0].pattern.logoDataUrl?.startsWith('data:image/png'));
  await centerMode.selectOption('screen');
  assert.equal(await page.evaluate(() => window.editorTests.state().screens[0].pattern.badgeText), '1');
  await page.evaluate(() => window.editorTests.loadRotationPreview());
  const rotation = page.getByText('Rotation', { exact: true }).locator('..').locator('input');
  await rotation.fill('30'); await rotation.blur();
  assert(await page.evaluate(() => {
    const s = window.editorTests.state().screens[0], a = s.rotation * Math.PI / 180;
    return s.rotation === 30 && s.width === 192 && s.height === 192 && Math.abs(s.x + s.width / 2 * Math.cos(a) - s.height / 2 * Math.sin(a) - 200) < 0.003 && Math.abs(s.y + s.width / 2 * Math.sin(a) + s.height / 2 * Math.cos(a) - 200) < 0.003;
  }), 'Rotation field preserves center and local dimensions');
  await page.evaluate(() => window.editorTests.state().undo());
  await page.waitForFunction(() => window.editorTests.state().screens[0].rotation === 45);
  await page.screenshot({ path: join(qaDir, 'rotation-editor.png') });
  await page.getByLabel('Import Resolume XML', { exact: true }).setInputFiles('tests/fixtures/resolume.xml');
  await page.getByRole('status').filter({ hasText: '4 slice' }).waitFor();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'EXPORT NEW LAYOUT XML' }).click();
  assert((await download).suggestedFilename().endsWith('.xml'));
  await page.evaluate(xml => {
    window.linkedTestXml = xml;
    window.showOpenFilePicker = async () => [{ name: 'linked.xml', getFile: async () => new File([window.linkedTestXml], 'linked.xml', { type: 'application/xml' }) }];
  }, fixture);
  await page.getByRole('button', { name: 'LINK XML', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'AUTO SYNC' }).waitFor();
  await page.evaluate(() => {
    const state = window.editorTests.state();
    const screen = state.screens.find(s => s.metadata.resolumeSource === 'linked.xml');
    state.updateScreen(screen.id, { pattern: { ...screen.pattern, accentColor: '#123456' } });
    window.linkedTestXml = window.linkedTestXml.replaceAll('x="320"', 'x="304"');
  });
  await page.waitForFunction(() => window.editorTests.state().screens.some(s => s.metadata.resolumeSource === 'linked.xml' && s.x === 304 && s.pattern.accentColor === '#123456'));
  await page.getByRole('button', { name: 'STOP AUTO SYNC', exact: true }).click();
  assert(await page.evaluate(() => window.editorTests.state().screens.filter(s => s.metadata.resolumeSource === 'linked.xml').length === 4));
  await page.screenshot({ path: join(qaDir, 'editor.png'), fullPage: true });
  const mp4 = page.waitForEvent('download');
  await page.evaluate(() => window.editorTests.recordSample());
  const file = await mp4; await file.saveAs(join(qaDir, 'sample.mp4'));
  assert((await readFile(join(qaDir, 'sample.mp4'))).length > 1000);
  assert.deepEqual(errors, []);
  console.log('PASS: parser, schema persistence, sync/undo, render, React controls, XML download, file-link auto sync, MP4 recording');
} finally { await browser?.close(); server.close(); }
